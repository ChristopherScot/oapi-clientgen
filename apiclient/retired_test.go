// A retired file as it sits in a consumer's repo today: the header
// this package writes, over a body it no longer renders.
//
// Built from Header rather than pasted, so this fixture cannot be the
// one place that still carries an outdated copy of the wording - the
// failure it exists to catch. The body is arbitrary; only the header
// decides whether the file may be deleted.
var retiredFile = apiclient.Header("//") + "\npackage api\n\nfunc TestX(t *testing.T) {}\n"

// writingGo is the Go set as a caller renders it, which is what
// RemoveRetired compares against. Nothing retired is in it.
func writingGo(t *testing.T) []apiclient.File {
	t.Helper()
	files, err := apiclient.Go(apiclient.Params{
		Name: "x", Version: "1.0.0", Package: "api", ImportPath: "example.com/x",
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

// A file this package used to write and no longer does has to be
// removed, not merely stopped. Otherwise it stays in every repo that
// ever ran the generator, owned by nobody, drifting from a template
// that keeps moving, while still telling its reader not to edit it.
func TestRetiredFilesAreRemoved(t *testing.T) {
	// Named, not ranged over Retired: a test that reads its subject
	// from the list under test cannot notice the list losing an entry,
	// it just checks less.
	retired := []string{"client_test.go", "paging_test.go"}

	dir := t.TempDir()
	for _, name := range retired {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(retiredFile), 0o644); err != nil {
			t.Fatalf("writing the stale %s: %v", name, err)
		}
	}

	removed, err := apiclient.RemoveRetired(dir, writingGo(t))
	if err != nil {
		t.Fatalf("RemoveRetired(%q): %v", dir, err)
	}

	for _, name := range retired {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Errorf("after RemoveRetired(%q), %s still exists; want it gone - "+
				"it is no longer generated, so nothing will update it again", dir, name)
		}
		if !slices.Contains(removed, name) {
			t.Errorf("RemoveRetired(%q) did not report removing %s; "+
				"the caller cannot tell the consumer what it did", dir, name)
		}
	}
}

// Only files this package wrote. A consumer who writes their own
// client_test.go beside a generated client is doing a reasonable
// thing, and a generator that deletes it is not.
func TestAHandWrittenFileSurvives(t *testing.T) {
	for _, tc := range []struct{ name, body string }{
		{"no marker at all", "package api\n\n// mine, not the generator's\n"},
		// The file a consumer is MOST likely to write: a replacement
		// that names what it replaced. Scanning the whole body for the
		// marker reads this as a claim of ownership and deletes it.
		{"mentions the generator in prose",
			"package api\n\n// Replaces the one Generated by homelabctl, which was wrong.\n" +
				"func TestMine(t *testing.T) {}\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			mine := filepath.Join(dir, "client_test.go")
			if err := os.WriteFile(mine, []byte(tc.body), 0o644); err != nil {
				t.Fatalf("writing the hand-written file: %v", err)
			}

			removed, err := apiclient.RemoveRetired(dir, writingGo(t))
			if err != nil {
				t.Fatalf("RemoveRetired(%q): %v", dir, err)
			}
			if len(removed) != 0 {
				t.Errorf("RemoveRetired(%q) removed %v; want nothing", dir, removed)
			}

			got, err := os.ReadFile(mine)
			if err != nil {
				t.Fatalf("a hand-written client_test.go was deleted: %v", err)
			}
			if string(got) != tc.body {
				t.Error("a hand-written client_test.go was modified")
			}
		})
	}
}

// The usual case: nothing to do, and nothing to report. A service
// scaffolded after these were dropped never had them.
func TestRemovingWhatIsNotThereIsNotAnError(t *testing.T) {
	dir := t.TempDir()
	removed, err := apiclient.RemoveRetired(dir, writingGo(t))
	if err != nil {
		t.Errorf("RemoveRetired(%q) on an empty directory: %v", dir, err)
	}
	if len(removed) != 0 {
		t.Errorf("RemoveRetired(%q) = %v; want nothing", dir, removed)
	}
}

// Retired must name nothing any list still ships, or the generator
// would write a file and then immediately delete it.
func TestRetiredNamesNothingStillShipped(t *testing.T) {
	p := apiclient.Params{
		Name: "x", Version: "1.0.0", Package: "api", ImportPath: "example.com/x",
	}
	shipped := map[string]bool{}
	for _, set := range []func(apiclient.Params) ([]apiclient.File, error){
		apiclient.Go, apiclient.TypeScript,
	} {
		files, err := set(p)
		if err != nil {
			t.Fatal(err)
		}
		for _, f := range files {
			shipped[f.Path] = true
		}
	}
	for _, name := range apiclient.Retired() {
		if shipped[name] {
			t.Errorf("%s is in Retired and still shipped: it would be written, then deleted", name)
		}
	}
}

// Every file the generator writes names the tool that wrote it.
//
// Documentation now, not a decision: deleting a retired file asks the
// inventory, not the file. But a reader who opens one of these in a
// repo that did not write it needs to be told where it came from, and
// they are rendered from different templates so one missing header is
// a plausible mistake.
func TestEveryGeneratedFileNamesTheGenerator(t *testing.T) {
	p := apiclient.Params{
		Name: "x", Version: "1.0.0", Package: "api", ImportPath: "example.com/x",
	}
	for _, set := range []struct {
		name  string
		files func(apiclient.Params) ([]apiclient.File, error)
	}{
		{"Go", apiclient.Go},
		{"TypeScript", apiclient.TypeScript},
		{"GoTests", apiclient.GoTests},
		{"TypeScriptTests", apiclient.TypeScriptTests},
	} {
		files, err := set.files(p)
		if err != nil {
			t.Fatal(err)
		}
		for _, f := range files {
			if !strings.Contains(f.Body, apiclient.GeneratedMarker) {
				t.Errorf("%s/%s does not name the generator, so a reader who finds it "+
					"in their repo cannot tell where it came from", set.name, f.Path)
			}
		}
	}
	if !strings.Contains(apiclient.GeneratedHeader(), apiclient.GeneratedMarker) {
		t.Error("GeneratedHeader, which MarkGenerated writes, does not name the generator")
	}
}

// The list decides what RemoveRetired deletes from a consumer's repo,
// so a caller must not be able to change it.
func TestRetiredCannotBeChangedByACaller(t *testing.T) {
	got := apiclient.Retired()
	if len(got) == 0 {
		t.Fatal("Retired() is empty")
	}
	got[0] = "client.go"

	if again := apiclient.Retired()[0]; again == "client.go" {
		t.Error("writing to the returned slice changed the package's own list")
	}
}

// A test template that is never registered renders nowhere and runs
// nowhere, and the suite stays green because it was never asked. That
// is how paging.test.ts shipped dead: the runner named one file, so the
// repeated-cursor guard could be deleted with every test passing.
//
// Compares names, not counts. Counting alone passes when one template
// is registered twice and another not at all, which is the same defect
// wearing the right total.
func TestEveryTestTemplateIsRegistered(t *testing.T) {
	for _, c := range []struct {
		glob string
		// dst is what the registry should call the file a template
		// renders: ts_paging_test.ts.tmpl -> paging.test.ts.
		dst    func(stem string) string
		render func(apiclient.Params) ([]apiclient.File, error)
	}{
		{
			glob:   "ts_*_test.ts.tmpl",
			dst:    func(stem string) string { return stem + ".test.ts" },
			render: apiclient.TypeScriptTests,
		},
		{
			glob:   "go_*_test.go.tmpl",
			dst:    func(stem string) string { return stem + "_test.go" },
			render: apiclient.GoTests,
		},
	} {
		paths, err := filepath.Glob(c.glob)
		if err != nil {
			t.Fatal(err)
		}
		if len(paths) == 0 {
			t.Fatalf("no %s found; this test is looking in the wrong place", c.glob)
		}

		var want []string
		for _, p := range paths {
			// ts_paging_test.ts.tmpl -> paging
			stem := strings.TrimSuffix(filepath.Base(p), ".tmpl")
			stem = strings.TrimSuffix(strings.TrimSuffix(stem, ".ts"), ".go")
			stem = strings.TrimSuffix(stem, "_test")
			_, stem, _ = strings.Cut(stem, "_") // drop the ts_/go_ prefix
			want = append(want, c.dst(stem))
		}

		rendered, err := c.render(apiclient.Params{
			Name: "probe", Version: "1.0.0", Package: "api",
			ImportPath: "probe-client", Published: true,
		})
		if err != nil {
			t.Fatal(err)
		}
		var got []string
		for _, f := range rendered {
			got = append(got, f.Path)
		}

		slices.Sort(want)
		slices.Sort(got)
		if !slices.Equal(got, want) {
			t.Errorf("%s renders %v, want %v: either a template is missing from the "+
				"registry, where it renders nowhere and its tests never run, or the "+
				"registry renders it under a name this test does not expect",
				c.glob, got, want)
		}
	}
}
